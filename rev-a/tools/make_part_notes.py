"""Write _tools/pcb_dashboard/part_notes.json for Board Boxes Info mode from rev A's circuit table.

Purpose text comes straight from circuit.py. Possible issues are the open items from
rev-a/README.md, attached to the parts they concern. Re-run after changing either.
"""
import json
import re
from pathlib import Path

import circuit

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "_tools" / "pcb_dashboard" / "part_notes.json"

ISSUES = {
    "F1": ["No part chosen yet: needs an SMD fuse rated at least 150 V DC at the charge current."],
    "Q1": ["Part not confirmed: must be fully on at the VOM1271's 7.8 V minimum gate drive (candidate IPT111N20NFD)."],
    "Q2": ["Part not confirmed: must be fully on at the VOM1271's 7.8 V minimum gate drive (candidate IPT111N20NFD)."],
    "U5": ["Pin 4 is assumed to be the + output; check with a meter on the first unit.",
           "Slow turn-on, about 10 ms for two TOLL gates."],
    "U4": ["Sees 134.4 V at full charge against a 140 V operating limit; only the R9/C3/C4 filter protects it."],
    "U11": ["Its upper side powers up when GPIO9 goes low, and the firmware reads right away (4 retries). It may need a short delay."],
    "U12": ["Its upper side powers up when GPIO9 goes low, and the firmware reads right away (4 retries). It may need a short delay."],
    "R1": ["Not routed yet: pad 2 (CHG_SRC) still needs a link to the source pour."],
    "U_BQ1": ["Not routed yet: pin 17 (GND) still needs a link to the ground plane."],
    "D2": ["Not routed yet: pad 1 (SW) still needs a link to the switch-node track."],
    "R_SH1": ["Check the current sign on the bench: the firmware expects SRP on the battery side (PCB_VERSION 2)."],
}
for k in range(1, 5):
    ISSUES[f"J_CELL{k}"] = ["Pin order copied from the old board; check it against the harness by continuity."]


def main():
    rows = []
    for p in circuit.PARTS:
        rows.append({"match": re.escape(p["ref"]), "purpose": p["purpose"],
                     "issues": ISSUES.get(p["ref"], [])})
    data = {
        "_about": "Per-part notes for Board Boxes Info mode, generated by rev-a/tools/make_part_notes.py "
                  "from rev-a/tools/circuit.py. Matched by full reference designator. Don't edit by hand.",
        "reva": rows,
        "shared": [],
    }
    OUT.write_text(json.dumps(data, indent=1, ensure_ascii=False), encoding="utf-8")
    print(f"wrote {len(rows)} notes to {OUT}")


if __name__ == "__main__":
    main()
