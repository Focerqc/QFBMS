"""Write rev A's .kicad_pro design rules and net classes, and its .kicad_dru custom rules.

Template: testing-BMS-designs Lean project (KiCad 10, 4 layers). Values:
  Default  0.15 mm clearance, 0.2 mm track, 0.5/0.25 mm via (JLC 4-layer standard)
  POWER    0.4 mm track: 3V3, 5V, 5V_BUCK, VBUS, GND, REG1/ISO supplies
  HV       0.6 mm clearance (IPC-2221B B2, 31-150 V): buck input/switch, FET gate
  CHARGE   1.5 mm track + 0.6 mm clearance: the charge-current path
Custom rule: upper-domain nets (CELL16..32 reference) keep 0.6 mm from GND-domain nets on the
outer layers; the router does not know this rule, DRC checks it.
"""
import json
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
REVA = HERE.parent
# Sibling checkout of github.com/Focerqc/testing-BMS-designs
TEMPLATE = HERE.parents[2] / "testing-BMS-designs" / "slave-18s-lean" / "adbms1818-slave-18s-lean.kicad_pro"
PRO = REVA / "qfbms-rev-a.kicad_pro"
DRU = REVA / "qfbms-rev-a.kicad_dru"

POWER = ["3V3", "5V", "5V_BUCK", "VBUS", "GND", "REG1_BQ1", "REG1_BQ2", "ISO_VCC2", "5V_EXT", "ISO_GND",
         "CELL16"]
HV = ["VIN_BUCK", "SW", "CHG_GATE"]
CHARGE = ["PACK_F", "BAT_POS", "CHG_POS", "CHG_SRC", "CHG_NEG"]


def netclass(name, clearance, track, via=0.5, drill=0.25, priority=0):
    return {"bus_width": 12, "clearance": clearance, "diff_pair_gap": 0.2, "diff_pair_via_gap": 0.25,
            "diff_pair_width": 0.2, "line_style": 0, "microvia_diameter": 0.3, "microvia_drill": 0.1,
            "name": name, "pcb_color": "rgba(0, 0, 0, 0.000)", "priority": priority,
            "schematic_color": "rgba(0, 0, 0, 0.000)", "track_width": track, "tuning_profile": "",
            "via_diameter": via, "via_drill": drill, "wire_width": 6}


def level(net):
    """Approximate potential in cells above GND (4.2 V each) at full charge."""
    n = net.lstrip("/")
    m = re.fullmatch(r"(?:CELL|TAP)(\d+)(?:_F)?", n)
    if m:
        return int(m.group(1))
    if n in ("BAT_BQ1", "BATD_BQ1", "COLL_BQ1", "PACK_BQ1", "CP1_BQ1"):
        return 16
    if n.endswith("_BQ2") or n in ("ISO_VCC2", "ISO_PG"):
        return 32 if n in ("BAT_BQ2", "BATD_BQ2", "COLL_BQ2", "PACK_BQ2", "CP1_BQ2") else 16
    if n in CHARGE + HV and n != "CHG_NEG":
        return 32
    return 0


def write_dru(coated=True):
    """IPC-2221B B2 (external) 31-150 V = 0.6 mm. Banks of 4 cells: nets in the same or
    neighbouring banks are at most 7 cells (29.4 V) apart; two or more banks apart get 0.6 mm."""
    sys.path.insert(0, str(HERE))
    import circuit
    nets = sorted({n for p in circuit.PARTS for n in p["pins"].values()})
    bank = {}
    for n in nets:
        bank.setdefault(level(n) // 4, []).append("/" + n)
    if coated:
        DRU.write_text(chr(10).join([
            "(version 1)",
            "# Generated by rev-a/tools/set_rules.py.",
            "# Rev A assumes conformal coating: IPC-2221B Table 6-1 column B4 (external,",
            "# permanent polymer coating) needs 0.13 mm for 31-150 V, covered by the 0.15 mm",
            "# board minimum. Pack-level nets keep 0.6 mm through the CHARGE and HV net classes.",
            "# Uncoated (B2, 0.6 mm by voltage bank): python set_rules.py --uncoated", ""]),
            encoding="utf-8")
        return
    rules = ["(version 1)",
             "# Generated by rev-a/tools/set_rules.py. Outer layers: 0.6 mm between nets more than",
             "# 7 cells apart (IPC-2221B B2, 31-150 V). Inner layers: B1 needs 0.1 mm, the 0.15 mm",
             "# board minimum covers it. Pads of one part are exempt in check_board.py (TI/ADI pinouts).", ""]
    banks = sorted(bank)
    for b in banks:
        far = [n for c in banks if c >= b + 2 for n in bank[c]]
        if not far:
            continue
        ca = " || ".join(f"A.NetName == '{n}'" for n in bank[b])
        cb = " || ".join(f"B.NetName == '{n}'" for n in far)
        rules += [f'(rule "Bank {b} (cells {4 * b}-{4 * b + 3}) vs banks {b + 2}+: >30 V"',
                  "  (layer outer)", "  (constraint clearance (min 0.6mm))",
                  f'  (condition "({ca}) && ({cb})"))', ""]
    DRU.write_text("\n".join(rules), encoding="utf-8")


def main():
    pro = json.loads(TEMPLATE.read_text(encoding="utf-8"))
    pro["meta"]["filename"] = PRO.name
    ds = pro["board"]["design_settings"]
    ds["drc_exclusions"] = []
    ds["rules"].update({"min_clearance": 0.15, "min_track_width": 0.15, "min_via_diameter": 0.45,
                        "min_through_hole_diameter": 0.2, "min_via_annular_width": 0.1,
                        "min_copper_edge_clearance": 0.3, "min_hole_clearance": 0.2,
                        "min_hole_to_hole": 0.25})
    ds["track_widths"] = [0.0, 0.2, 0.3, 0.4, 0.6, 1.0, 1.5]
    ds["via_dimensions"] = [{"diameter": 0.0, "drill": 0.0}, {"diameter": 0.5, "drill": 0.25},
                            {"diameter": 0.8, "drill": 0.4}]
    ns = pro["net_settings"]
    ns["classes"] = [netclass("Default", 0.15, 0.2, priority=2147483647),
                     netclass("POWER", 0.15, 0.4, priority=2),
                     netclass("HV", 0.6, 0.3, priority=1),
                     netclass("CHARGE", 0.6, 1.5, priority=0)]
    ns["netclass_patterns"] = ([{"netclass": "POWER", "pattern": f"/{n}"} for n in POWER]
                               + [{"netclass": "HV", "pattern": f"/{n}"} for n in HV]
                               + [{"netclass": "CHARGE", "pattern": f"/{n}"} for n in CHARGE])
    ns["netclass_assignments"] = None
    pro["sheets"] = [["6f1c2a40-3b7e-4c1d-9a55-0d4e2b7a0001", "Root"]]
    for k in ("text_variables",):
        pro[k] = {}
    PRO.write_text(json.dumps(pro, indent=2), encoding="utf-8")

    write_dru(coated="--uncoated" not in sys.argv)
    print("wrote", PRO.name, DRU.name)


if __name__ == "__main__":
    main()
